-- Step6: 既存テナントを pro へ上げる。
--
-- **これが無いと、Step6 を配備した瞬間に全テナントの上限が厳しくなる。** `Tenant.plan` は
-- Step0 から `@default(free)` で存在したが**どこからも読まれていなかった**ので、Step4 / Step5 まで
-- 動いていた配備の行はすべて free のままになっている。Step6 で free が意味を持った途端に、
-- 中継の枠が 600 → 60 回/分、有効なガードレールのルールが 50 → 5 件、エージェント数が
-- 無制限 → 3 件へ絞られ、監査ログの改ざん検証は 403 になる（＝今まで通っていた要求が 429 / 409 / 403）。
--
-- `src/domain/plan.ts` の pro は Step4 までの固定値と同じなので、既存の行を pro へ上げると
-- 「プラン別にして緩くなった利用者はいない」が実際に成り立つ（ADR-0012 決定 1）。
--
-- **新しく作るテナントは free のまま**（列の既定値と `createWithAdmin` は変えない）。
-- マイグレーションは 1 度しか走らないので、この UPDATE が当たるのは
-- 「Step6 より前から存在した行」だけ。空の DB では 0 行で何もしない。
--
-- 上げたくない配備（新規インストール直後に試用で始めたい等）は、適用後に
-- `PATCH /api/v1/tenants/{tenantId}`（プラットフォーム管理者）で下げられる。
