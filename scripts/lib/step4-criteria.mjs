// 発火から停止までの上限 (ミリ秒)。受け入れ基準「ルール発火から停止まで ≦ 3 秒」そのもの。
// **ミリ秒で持つ**のは、ベンチが測るのも `performance.now()` の差 (ミリ秒) だから。
// ロードマップの散文「3 秒」との突き合わせは tests/docs-gate.test.ts が 1000 で割って行う
export const GUARDRAIL_STOP_MAX_MS = 3_000;

// 発火のテストの名前の接頭辞。`tests/guardrail-rule.test.ts` が
// 「発火: <種別>」という describe でまとめ、ゲートは **RuleKind の全種類ぶんが pass しているか**を
// この接頭辞で照合する (料金表からモデル名を導くのと同じ形。種別を足してテストを書き忘れたら落ちる)
export const FIRING_TEST_PREFIX = '発火: ';

// 改ざん検知のテストの名前の接頭辞。`tests/audit-chain.test.ts` が
// 「改ざん検知: … <壊れ方> で落ちる」という名前でまとめ、ゲートは **連鎖の壊れ方の全種類ぶんが
// pass しているか**を照合する。受け入れ基準「監査ログの改ざん検知テスト pass」そのもの。
//
// **壊れ方ごとに見る**のは、「検知できる」と言えるのは壊し方を列挙して 1 つずつ試したときだけ
// だから。1 本でも pass していればよい形にすると、壊れ方を足した人がテストを書き忘れても
// ゲートは緑のまま「その壊し方は検知できない」状態で出荷できる
export const TAMPER_TEST_PREFIX = '改ざん検知: ';

// E2E のテスト名 (完全一致ではなく、この文字列を含む pass したテストを探す)。
// 受け入れ基準「E2E で『登録→実行→超過→停止→復帰』が通る」そのもので、
// **1 本のテストで 5 段を順に通す** (段ごとに分けると「途中で切れている」ことに気付けない)
export const GUARDRAIL_E2E_TEST_NAME = 'E2E: 登録→実行→超過→停止→復帰';
