// ─────────────────────────────────────────────

/**
 * 既知の問題を記録する文書 (リポジトリ相対)。
 *
 * **「Issue 管理」をリポジトリの中で機械検査できる形に解釈する**（ゲート運用ルール 4）。
 * GitHub の Issue はゲートから読めない（ネットワークに出られない・権限が要る）ので、
 * **未解決のバグはこの文書の表に書く**ことを運用の約束にし、ゲートは「表が空であること」を見る。
 *
 * **文書だけを見ると編集 1 行で黙らせられる**ので、独立な手がかり（下のマーカー）と
 * 併せて見る。詳細は ADR-0013。
 */
export const KNOWN_ISSUES_DOC = 'docs/known-issues.md';

/** 既知の問題の表が始まる見出し (この下に行があれば未解決のバグがある) */
export const KNOWN_ISSUES_HEADING = '## 未解決のバグ';

/**
 * ソースに残した「未解決の欠陥」の印。1 つでもあれば既知バグ 0 ではない。
 *
 * **`TODO` は含めない** — このリポジトリは「後の Step でやる」設計上の宿題を ADR と
 * コメントに書く流儀で、それらは欠陥ではない（含めると実行不能な要求になり、検出網が
 * 緩められる側に倒れる）。印すのは「いま壊れていると分かっているもの」だけ。
 */
export const KNOWN_BUG_MARKERS = ['FIXME', 'XXX', 'BUG:', 'HACK:'];

/** マーカーを探すディレクトリ (リポジトリ相対。実行されるコードと検出網のすべて) */
export const KNOWN_BUG_MARKER_DIRS = ['src', 'tests', 'scripts', 'e2e', 'prisma'];
