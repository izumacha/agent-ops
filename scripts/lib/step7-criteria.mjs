// ─────────────────────────────────────────────
// 基準① クリーン環境で `docker compose up` → 5 分以内にデモ動作
// ─────────────────────────────────────────────

/**
 * デモが動くまでの上限 (ミリ秒)。
 *
 * **基準の文は「クリーン環境で `docker compose up` → 5 分以内」で、2 つの経路が同じ上限を見る**:
 * - CI の `docker-smoke` ジョブ: `up -d --build` の開始時刻から数えてデモの筋が通るまで。
 *   こちらが**基準そのもの**（イメージのビルドとマイグレーション適用を含む）。
 * - `npm run bench:demo-ready`: 本番ビルドを起動してからデモの筋が通るまで。
 *   Docker を使わない機械でも回せる**部分集合**で、ゲートが毎回確かめるのはこちら。
 *
 * 部分集合のほうが必ず速いので「ゲートが緑でも CI が赤」はありうる（逆は無い）。
 * 解釈はゲート運用ルール 4 に従い `docs/roadmap.md` と ADR-0013 に書く。
 */
export const DEMO_READY_MAX_MS = 5 * 60 * 1_000;

/**
 * デモの筋として通す段の数。
 *
 * **数を固定するのが要点** — 段を削って速くした計測は「デモが動いた」の証拠にならない。
 * 中身（どの API をどの順で叩くか）は `scripts/lib/demo-flow.mjs` の `DEMO_STEPS` が持ち、
 * ここは「その件数ぶん成功したか」だけを見る（写しを 2 つ持たないため、件数もそちらから導く）。
 */
export const DEMO_STEP_COUNT = 6;

// ─────────────────────────────────────────────
// 基準② 同時 100 リクエストでエラー率 < 1%
// ─────────────────────────────────────────────

/** 同時に張る接続の数 (基準の「同時 100 リクエスト」) */
export const CONCURRENCY_CONNECTIONS = 100;

/**
 * 計測する長さ (秒)。
 *
 * **短すぎると「起動直後の数十件」しか測らない** ので、接続数の 10 倍以上の要求が流れる長さにする
 * （下の `CONCURRENCY_MIN_REQUESTS` が実際に流れた件数を門番として見る）。
 */
export const CONCURRENCY_DURATION_SECONDS = 10;

/**
 * 許すエラー率 (%)。基準は「< 1%」なので、**これを超えたら不合格**（等号は含めない）。
 *
 * 数えるのは 2xx 以外の応答と、応答が返らなかった要求（接続エラー・タイムアウト）の合計。
 * **2xx 以外だけを数えると接続が切られた分が「無かったこと」になる**（autocannon は
 * `errors` を別に数える）。
 */
export const CONCURRENCY_MAX_ERROR_PERCENT = 1;

/**
 * 計測が成立したとみなす最小の要求数。
 *
 * **これが無いと「3 件流して 0 件失敗」で合格できる** — エラー率は割合なので、分母が小さいほど
 * 緩くなる（1 件でも失敗すれば 1/3 = 33% だが、そもそも流れていなければ 0%）。接続数の 10 倍を
 * 下限に置く（10 秒で 1 接続あたり 10 件は、この API の実測から見て十分低い水位）。
 */
export const CONCURRENCY_MIN_REQUESTS = CONCURRENCY_CONNECTIONS * 10;

// ─────────────────────────────────────────────
