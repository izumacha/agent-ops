// レート制限の記録の Port（契約）。実装は adapters/memory と adapters/prisma（ADR-0015）。
//
// **なぜ data 層へ出したか。** 以前はインプロセスの `Map` が記録を持っていたので、同じテナントの
// 要求が別のインスタンスへ振られると枠が別々に数えられ、水平スケールすると「インスタンス数 × 上限」
// まで通った（ADR-0010 の宿題）。費用を払う単位はテナントなので、枠も**配備全体で 1 つ**でなければ
// 意味を持たない。
//
// **「窓の中の件数を数えて、上限未満なら 1 行足す」を 1 回の操作で行う。** 読んでから書く形に分けると、
// 同時に届いた 2 本がどちらも「上限未満」を読んで両方が通る（`agents.create` の件数上限と同じ理由）。

/** 1 回の消費の入力 */
export interface RateLimitConsumeInput {
  /**
   * 数える単位（`tenant:<id>` か `platform`）。
   * **偽装できる値（IP・ヘッダ）を渡さない**（`rateLimitKeyFor` が認証済みの主体から作る）。
   */
  key: string;
  /**
   * 枠の種類（`standard` / `fanOut` / `outbound` / `heavyRead`）。
   *
   * **共有の枠は種類を問わない合計**で、追加の枠はこの種類だけの合計。
   * 1 回の呼び出しは**行を 1 本だけ**足し、その行が両方の数に入る（置き換えではなく「加えて」消費する）。
   */
  tier: string;
  /**
   * 窓の長さ（ミリ秒）。
   *
   * **「いま」と窓の下端を呼び出し側から渡さない**のが要点。記録が配備全体で 1 つでも、
   * 時刻が**アプリのインスタンスごとの壁時計**だと枠は再び台数分に割れる — 90 秒遅れている
   * インスタンスが入れた行は、進んでいるインスタンスの窓から外れて数えられない。
   * 時刻は**記録側（1 つの DB、または memory の表）の時計**が決める（`RateLimitConsumeResult.at`）。
   */
  windowMs: number;
  // 共有の枠の上限（正の整数）
  sharedLimit: number;
  // 追加の枠の上限（持たない種類は null）
  extraLimit: number | null;
}

/**
 * 1 回の消費の結果。
 *
 * **件数は「今回を足す前」の値**を返す（上限との比較が呼び出し側でも再現できるようにする）。
 * `*Oldest` は窓の中で最も古い記録の時刻で、断ったときの `Retry-After` を決めるのに使う。
 */
export interface RateLimitConsumeResult {
  // 通してよいか（false のとき、記録は 1 行も増えていない）
  allowed: boolean;
  /**
   * 記録側が「いま」として使った時刻。
   *
   * **待ち時間の計算はこれを基準にする** — アプリの時計と混ぜると、ずれているインスタンスが
   * 返す `Retry-After` だけがずれる（`*Oldest` は記録側の時計で入った値）。
   */
  at: Date;
  /**
   * **枠を数えられなかったので断ったか。**
   *
   * 同じキーの判定が混み合って順番待ちが上限（実装側で決める短い待ち時間）を超えたときに `true`。
   * `allowed` は必ず `false` で、件数は 0・`*Oldest` は `null`（数えられていないので値が無い）。
   * **待たせ続けない**のが要点 — 判定が終わるまで接続を握ったままにすると、1 テナントの混雑が
   * 接続プールを占めて**無関係なテナントの要求まで失敗させる**（レート制限が、止めるべき
   * 濫用の増幅器になる）。この件数の要求が同じキーに同時に来ている時点でそのテナントは
   * 上限を大きく超えているので、断るのは安全側（§9 fail-closed）。
   */
  contended: boolean;
  // 窓の中の件数（種類を問わない合計 / この種類だけ）
  sharedCount: number;
  extraCount: number;
  // 窓の中で最も古い記録（1 件も無ければ null）
  sharedOldest: Date | null;
  extraOldest: Date | null;
}

// レート制限の記録 Port
export interface RateLimitPort {
  /**
   * 1 回の呼び出しを数えて、通してよいかを返す。
   *
   * 約束:
   * - **断った呼び出しは数えない**（数えると断られ続けるあいだ窓が延びて永久に通れない）
   * - 窓の下端より古い記録は数えない（スライディングウィンドウ。**過去側が半開**）
   * - 共有の枠と追加の枠の**両方**が上限未満のときだけ通す
   * - 通すときは**行を 1 本だけ**足す（その行が両方の数に入る）
   * - 件数は今回を足す前の値を返す
   * - 時刻は**記録側の時計**で決め、使った値を `at` で返す
   * - **同じキーの判定は直列化する。** 「数えて条件付きで足す」を 1 文に収めるだけでは足りない —
   *   PostgreSQL の READ COMMITTED では文のスナップショットが文の開始時点で固まるので、同時に
   *   走った別の文の挿入が見えない（実測で上限 3 に対して 10 本同時なら 6 本が通った）。
   *   守っているのは「高くつく処理の回数」なので、**同時実行数に比例して緩む上限は上限として
   *   機能しない**（`heavyRead` は毎分 10 回なのに 100 本同時なら 100 回通りうる）。
   *   件数の上限（`agents.create`）と同じ立場を取り、**キーごとに**直列化する（別のキーは独立）。
   * - **順番待ちは短く打ち切る**（`contended`）。待たせ続けると接続プールを占め、1 テナントの
   *   混雑が無関係なテナントの要求を失敗させる。
   */
  consume(input: RateLimitConsumeInput): Promise<RateLimitConsumeResult>;

  /**
   * 窓から外れた記録をまとめて消す（戻り値は消した件数）。
   *
   * `consume` は**そのキーの**期限切れだけを同じ操作の中で片付けるので、通常は表が膨らまない。
   * これが要るのは**二度と来ないキー**（解約したテナント・一度だけ来た主体）の記録で、
   * 定期掃き（ADR-0015 の宿題）が呼ぶ。
   *
   * **1 回で消す件数に上限を置く**（§8「一覧取得は必ず上限・ページネーションを持たせる」と同じ
   * 理由）。無制限の `DELETE` は、溜まった行数が多いときに長いトランザクションと大きなロックに
   * なり、同時に走る `consume` の per-key の掃き出しと順序が交差して待ち合わせうる。
   * 呼び出し側は「`limit` 件未満が返るまで」繰り返す。
   * @param before この時刻以前（同値を含む）の記録を消す
   * @param limit 1 回で消す件数の上限（正の整数）
   * @returns 実際に消した件数
   */
  sweep(before: Date, limit: number): Promise<number>;
}
