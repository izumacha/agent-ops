// 環境変数から読む「秘密」の門番を 1 か所に集めたモジュール。
//
// **3 つ目の写しが出た時点で共通化した**（§6 の「2〜3 箇所目で重複したら共通化する」）。
// 監査ログの鍵・課金の共有シークレット・監視用トークンがどれも同じ判断を持っていて、
// しかも 3 つ目は「未設定」の判定だけ別の綴り（`!configured`）になっていた。写しのままだと
// 4 つ目を足す人が同じ判断を書き直し、**前後の空白を落とす・未設定と短すぎを分ける・
// 503 へ倒す**のどれかが 1 か所だけ抜ける（この PR はまさにその 3 つを順に踏んで直している）。
//
// **共通化するのは「判断」だけで、「どの出来事を出すか」は呼び出し側に残す。**
// 出来事の名前を引数で受け取る形（`missingEvent: LogEventName` のような表）にすると、
// 出口へ渡る第 1 引数がこのファイルの中では変数になるので、
// `tests/error-logging.test.ts` の 2 つの網（出口の実引数は語彙のキーのリテラルだけ／
// 語彙に宣言した出来事はどれも実際に出している）が**その 6 つについて何も見なくなる**
// （実測で前者は赤、後者は「宣言だけで出していない」と報告した）。
// リテラルを呼び出し側へ残せば、`docs/deploy.md` の一覧をソースから導いている検査も効き続ける。

/** 秘密が使えない理由（**直し方が違う**ので 2 つに分ける: 変数を足すのか、値を作り直すのか） */
export type SecretGateRejection = 'missing' | 'too_short';

/**
 * 秘密を返す。使えなければ `reject` が投げる（**fail-closed**）。
 *
 * - **前後の空白を落とす。** 落とさないと、貼り付けの改行 1 つで「長さの門番は通るのに
 *   ハッシュ比較は完全な不一致」になり、正しい値を持っている相手が永久に弾かれる。
 * - **順番を固定する**（未設定を先に見る）。逆にすると未設定が「短すぎる」として報告され、
 *   運用者は在りもしない短い値を探す。
 * - **`reject` は `never` を返す**ので、呼び出し側が記録だけして投げ忘れる形を型が拒む
 *   （戻り値を `void` にすると、記録したのに素通りして秘密なしで先へ進む）。
 * @param value 環境変数から読んだ生の値
 * @param minLength 使える最小の長さ（`src/lib/constants.ts` の定数を渡す）
 * @param reject 使えないときに記録して投げる関数（理由ごとに別の出来事を出す）
 * @returns 使える秘密（前後の空白を落とした値）
 */
export function requireConfiguredSecret(
  value: string | undefined,
  minLength: number,
  reject: (reason: SecretGateRejection) => never,
): string {
  // 生の値を読み、前後の空白を落とす
  const configured = value?.trim();
  // 未設定・空文字は設定されていないのと同じ（**こちらを先に見る**）
  if (configured === undefined || configured === '') reject('missing');
  // 短すぎる値は総当たりで求められるので使わない
  if (configured.length < minLength) reject('too_short');
  // 使える秘密
  return configured;
}
